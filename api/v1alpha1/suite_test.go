// These exercise the CRD-embedded CEL rules directly against envtest's apiserver -- no
// controller or controller-runtime webhook is under test here, only the schema generated by
// "make manifests" -- plus one ValidatingAdmissionPolicy (config/admission): the
// kubeProxy-switch guard, which CRD-embedded CEL cannot express. That policy is
// loaded from its own source file below, so the test exercises the exact manifest a real
// deploy installs rather than a copy that could drift from it.
var (
	k8sClient client.Client
	testEnv   *envtest.Environment
)

// admissionPolicyPath is config/admission/kubeproxy-switch-policy.yaml, loaded as-is so this
// suite and a real deploy enforce the same rule.
const admissionPolicyPath = "../../config/admission/kubeproxy-switch-policy.yaml"

// asUser is a client that acts as user, in the groups the admission policies' tests need.
func asUser(user string) client.Client {
	cfg := rest.CopyConfig(testEnv.Config)
	cfg.Impersonate = rest.ImpersonationConfig{UserName: user, Groups: []string{"system:masters", "system:authenticated"}}

	c, err := client.New(cfg, client.Options{Scheme: clientgoscheme.Scheme})
	Expect(err).NotTo(HaveOccurred())

	return c
}

// expectAdmitted asserts that err is nil when accepted, and an error when not.
func expectAdmitted(err error, accepted bool) {
	GinkgoHelper()

	if accepted {
		Expect(err).NotTo(HaveOccurred())
	} else {
		Expect(err).To(HaveOccurred())
	}
}

// installAdmissionPolicy creates every object in the file at path through c against the
// test apiserver. ValidatingAdmissionPolicy and ValidatingAdmissionPolicyBinding are built-in
// API types, not CRDs, so -- unlike config/crd/bases -- there is no envtest option to install
// them from a directory; creating them is enough, no scheme registration required since the
// client talks to them as unstructured.
func installAdmissionPolicy(c client.Client, path string) {
	data, err := os.ReadFile(path)
	Expect(err).NotTo(HaveOccurred())

	dec := k8syaml.NewYAMLOrJSONDecoder(bytes.NewReader(data), 4096)
	for {
		var obj map[string]any
		if err := dec.Decode(&obj); err != nil {
			if errors.Is(err, io.EOF) {
				break
			}
			Expect(err).NotTo(HaveOccurred())
		}
		if obj == nil {
			continue
		}
		Expect(c.Create(context.Background(), &unstructured.Unstructured{Object: obj})).To(Succeed())
	}
}

// awaitKubeProxyPolicyEnforced blocks until the apiserver actually rejects an unannotated
// kubeProxy switch. A ValidatingAdmissionPolicy is compiled and bound asynchronously after its
// create returns, so for a short window (long under CPU load) updates are admitted unchecked;
// without this wait the first spec that relies on the policy is flaky.
func awaitKubeProxyPolicyEnforced() {
	ctx := context.Background()
	probe := newClusterWithCNI(TalosClusterCNI{Preset: cniPresetCilium, KubeProxy: kubeProxyEnabled})
	Expect(k8sClient.Create(ctx, probe)).To(Succeed())
	Eventually(func() error {
		Expect(k8sClient.Get(ctx, client.ObjectKeyFromObject(probe), probe)).To(Succeed())
		// Flip whichever way the stored value is, so an admitted (unenforced) attempt cannot
		// leave the probe in a state where the next attempt is a no-op.
		if probe.Spec.CNI.KubeProxy == kubeProxyEnabled {
			probe.Spec.CNI.KubeProxy = kubeProxyReplaced
		} else {
			probe.Spec.CNI.KubeProxy = kubeProxyEnabled
		}
		return k8sClient.Update(ctx, probe)
	}, "30s", "100ms").ShouldNot(Succeed())
	Expect(k8sClient.Delete(ctx, probe)).To(Succeed())
}

func TestAPIs(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "v1alpha1 CRD validation suite")
}

var _ = BeforeSuite(func() {
	logf.SetLogger(zap.New(zap.WriteTo(GinkgoWriter), zap.UseDevMode(true)))

	testEnv = &envtest.Environment{
		CRDDirectoryPaths:     []string{filepath.Join("..", "..", "config", "crd", "bases")},
		ErrorIfCRDPathMissing: true,
	}

	cfg, err := testEnv.Start()
	Expect(err).NotTo(HaveOccurred())
	Expect(cfg).NotTo(BeNil())

	testScheme := runtime.NewScheme()
	Expect(AddToScheme(testScheme)).To(Succeed())

	k8sClient, err = client.New(cfg, client.Options{Scheme: testScheme})
	Expect(err).NotTo(HaveOccurred())
	Expect(k8sClient).NotTo(BeNil())

	installAdmissionPolicy(k8sClient, admissionPolicyPath)
	awaitKubeProxyPolicyEnforced()
})

var _ = AfterSuite(func() {
	By("tearing down the test environment")
	Expect(testEnv.Stop()).To(Succeed())
})
