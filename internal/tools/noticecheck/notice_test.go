package noticecheck

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

const (
	mplHeader    = "// " + mplMark + "\n// License, v. 2.0.\n//\n" + mplCopyright + "\n\n// Code generated by mirrorgen. DO NOT EDIT.\n\npackage p\n"
	apacheHeader = "/*\nCopyright 2026 maeshinshin.\n\n" + apacheMark + " ...\n*/\n\npackage p\n"
	crdYAML      = "description: 'Talos: BondConfig — https://docs.siderolabs.com/talos/v1.14/x'\n"
)

// TestLicenceTreatmentOfTheTree fails when a file that contains Talos-derived content lacks the treatment its
// kind of file takes, or NOTICE names a file that is not there.
func TestLicenceTreatmentOfTheTree(t *testing.T) {
	root, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		t.Fatalf("git rev-parse: %v", err)
	}

	dir := strings.TrimSpace(string(root))

	list, err := exec.Command("git", "-C", dir, "ls-files", "-z", "--cached", "--others", "--exclude-standard").Output()
	if err != nil {
		t.Fatalf("git ls-files: %v", err)
	}

	files := map[string]string{}

	for path := range strings.SplitSeq(string(list), "\x00") {
		if path == "" {
			continue
		}

		b, err := os.ReadFile(filepath.Join(dir, path))
		if err != nil {
			continue // listed but deleted from the tree
		}

		files[path] = string(b)
	}

	notice, err := os.ReadFile(filepath.Join(dir, "NOTICE"))
	if err != nil {
		t.Fatal(err)
	}

	for _, p := range check(files, string(notice)) {
		t.Error(p)
	}
}

// TestCheckNamesEachMistake runs check on a small tree that is right and on one edit of it for each way it can be wrong.
func TestCheckNamesEachMistake(t *testing.T) {
	good := func() map[string]string {
		return map[string]string{
			"api/gen.go":                    mplHeader,
			"api/plain.go":                  apacheHeader,
			"pkg/typedconfig/zz_deep.go":    strings.Replace(mplHeader, "by mirrorgen", "by controller-gen", 1),
			"config/crd/bases/talos.yaml":   crdYAML,
			"docs/reference/crds/talos.md":  "# T\n" + crdYAML,
			"internal/tools/kinds.go":       apacheHeader + "var _ = \"Talos: BondConfig\"\n",
			"docs/reference/crds/other.md":  "# no Talos schema here\n",
			"internal/handwritten/talos.go": apacheHeader + "import _ \"github.com/siderolabs/talos/pkg/machinery/config\"\n",
		}
	}
	notice := "Ichor\n\napi/gen.go\npkg/typedconfig/zz_deep.go\nconfig/crd/bases/talos.yaml\ndocs/reference/crds/talos.md\n"

	if p := check(good(), notice); len(p) != 0 {
		t.Fatalf("a correct tree was refused: %q", p)
	}

	cases := []struct {
		name   string
		edit   func(map[string]string, *string)
		expect string
	}{
		{"a derived Go file with an Apache block", func(f map[string]string, _ *string) {
			f["api/gen.go"] = strings.Replace(apacheHeader, "package p", "// Code generated by mirrorgen. DO NOT EDIT.\n\npackage p", 1)
		}, "api/gen.go: contains Talos-derived content but carries an Apache-2.0 block"},
		{"a derived Go file with no header", func(f map[string]string, _ *string) {
			f["api/gen.go"] = "// Code generated by controller-gen. DO NOT EDIT.\n\npackage p\n\nimport _ \"github.com/maeshinshin/ichor/pkg/typedconfig\"\n"
		}, "api/gen.go: contains Talos-derived content but its header has no MPL-2.0 notice"},
		{"a derived Go file without the copyright line", func(f map[string]string, _ *string) {
			f["api/gen.go"] = strings.Replace(f["api/gen.go"], mplCopyright, "// Copyright someone.", 1)
		}, "api/gen.go: the MPL-2.0 header lacks the line"},
		{"a derived Go file missing from NOTICE", func(_ map[string]string, n *string) { *n = strings.Replace(*n, "api/gen.go\n", "", 1) }, "api/gen.go: contains Talos-derived content but NOTICE does not list it"},
		{"a derived manifest missing from NOTICE", func(_ map[string]string, n *string) { *n = strings.Replace(*n, "config/crd/bases/talos.yaml\n", "", 1) }, "config/crd/bases/talos.yaml: holds Talos-derived schema"},
		{"a derived reference page missing from NOTICE", func(_ map[string]string, n *string) {
			*n = strings.Replace(*n, "docs/reference/crds/talos.md\n", "", 1)
		}, "docs/reference/crds/talos.md: holds Talos-derived schema"},
		{"a NOTICE path that no longer exists", func(f map[string]string, _ *string) { delete(f, "config/crd/bases/talos.yaml") }, "NOTICE names config/crd/bases/talos.yaml, which does not exist"},
		{"a file with both grants", func(f map[string]string, _ *string) {
			f["api/plain.go"] = "/*\n" + mplMark + "\n" + apacheMark + "\n*/\npackage p\n"
		}, "api/plain.go: the header grants both MPL-2.0 and Apache-2.0"},
		{"a file that is not derived and carries MPL", func(f map[string]string, _ *string) { f["api/plain.go"] = "// " + mplMark + "\npackage p\n" }, "api/plain.go: carries an MPL-2.0 notice but holds no Talos-derived content"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			f, n := good(), notice
			c.edit(f, &n)

			for _, p := range check(f, n) {
				if strings.Contains(p, c.expect) {
					return
				}
			}

			t.Errorf("no problem reported containing %q; got %q", c.expect, check(f, n))
		})
	}
}
