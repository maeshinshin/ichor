export type Lang = 'en' | 'ja'
export const langs: readonly Lang[] = ['en', 'ja']
// Each language names itself in itself, so the switch is findable by a person
// who cannot read the current one.
export const langNames: Record<Lang, string> = { en: 'English', ja: '日本語' }

const dicts: Record<Lang, Dict> = { en, ja }

export function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'ja'
}

// detectLang: a saved choice wins; otherwise the first browser language we
// have a dictionary for; otherwise English.
export function detectLang(saved: string | null | undefined, browser: readonly string[] | undefined): Lang {
  if (isLang(saved)) return saved
  for (const tag of browser ?? []) {
    const primary = tag.toLowerCase().split('-')[0]
    if (isLang(primary)) return primary
  }
  return 'en'
}

export type Params = Record<string, string | number>

export function translate(lang: Lang, key: Key, params?: Params): string {
  const s = dicts[lang][key]
  return params ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : s
}

// enumName translates a proto enum value name ("HANDED_OVER") if it has an
// entry, or returns undefined so the caller can fall back to the raw name.
export function enumName(lang: Lang, name: string): string | undefined {
  const key = `enum.${name}`
  return key in en ? dicts[lang][key as Key] : undefined
}
