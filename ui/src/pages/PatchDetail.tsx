// A Patch-shaped plain object, not the generated Message type: every field
// built here comes from form state, not a decoded response, so it never
// carries the generated type's own "$typeName" brand - MessageInitShape is
// the same loose, brand-free shape createClient's own call signatures
// already expect (confirmed against @connectrpc/connect's promise-client.d.ts).
type PatchInit = MessageInitShape<typeof PatchSchema>

// The layers a patch may actually set (CONFIG_LAYER_SYSTEM is generated by
// Ichor itself, never user-writable - architecture.md, "Patch layers"), each
// with the line that says what it selects.
const EDITABLE_LAYERS: { layer: ConfigLayer; descKey: Key }[] = [
  { layer: ConfigLayer.CLUSTER, descKey: 'patch.layerDesc.cluster' },
  { layer: ConfigLayer.ROLE, descKey: 'patch.layerDesc.role' },
  { layer: ConfigLayer.SELECTOR, descKey: 'patch.layerDesc.selector' },
  { layer: ConfigLayer.MACHINE, descKey: 'patch.layerDesc.machine' },
]

// The layer decides which target the patch has, so the form has no
// separate "target kind": lib/patchTarget works from this key.
function layerKeyOf(layer: ConfigLayer): LayerKey {
  switch (layer) {
    case ConfigLayer.CLUSTER:
      return 'cluster'
    case ConfigLayer.ROLE:
      return 'role'
    case ConfigLayer.SELECTOR:
      return 'selector'
    case ConfigLayer.MACHINE:
      return 'machine'
    default:
      return 'unset'
  }
}

let nextDocId = 1

// PatchDetail is both the create form (/config/new, name
// undefined) and the edit form (/config/:name) for a
// TalosConfigPatch, matching PatchService's own "full replace, no
// partial-field merge" shape (not
// through a generic schema-driven renderer - see).
export function PatchDetail({ name }: { name?: string }) {
  const { cluster: current, error: clusterError } = useCluster()
  const namespace = current?.ref?.namespace
  const cluster = current?.ref ? { namespace: current.ref.namespace, name: current.ref.name } : undefined
  const isNew = name === undefined

  const [loaded, setLoaded] = useState(isNew)
  const [loadError, setLoadError] = useState<ErrorShape | null>(null)

  const [patchName, setPatchName] = useState(name ?? '')
  const [layer, setLayer] = useState<ConfigLayer>(ConfigLayer.UNSPECIFIED)
  const [priority, setPriority] = useState(0)
  const [machines, setMachines] = useState<Machine[]>([])
  const [role, setRole] = useState('')
  const [labelSelectorText, setLabelSelectorText] = useState(stringifyLabelSelector(undefined))
  const [machineRef, setMachineRef] = useState('')
  const [documents, setDocuments] = useState<DocItem[]>([])

  const [saveError, setSaveError] = useState<ErrorShape | null>(null)
  const [saving, setSaving] = useState(false)

  const [preview, setPreview] = useState<{ rebootRequired: boolean; installTimeOnly: string[]; unsupported: string[] } | null>(null)
  // The form state the shown preview was run for (lib/patchDocs previewKey).
  const [previewedKey, setPreviewedKey] = useState<string | null>(null)
  const [previewError, setPreviewError] = useState<ErrorShape | null>(null)
  const [previewing, setPreviewing] = useState(false)

  // The machine picker lists the chosen cluster's machines.
  useEffect(() => {
    if (!cluster) {
      setMachines([])
      return
    }
    let cancelled = false
    machineClient.listMachines({ cluster }).then(
      (res) => !cancelled && setMachines(res.machines),
      () => !cancelled && setMachines([]),
    )
    return () => {
      cancelled = true
    }
  }, [cluster?.namespace, cluster?.name])

  useEffect(() => {
    if (isNew || !namespace) return
    let cancelled = false
    patchClient.getPatch({ patch: { namespace, name } }).then(
      (res) => {
        if (cancelled) return
        const p = res.patch
        if (!p) {
          setLoadError({ title: t('common.notFound'), detail: t('patch.noPatch') })
          return
        }
        setPatchName(p.ref?.name ?? name)
        setLayer(p.layer)
        setPriority(p.priority)
        applyTargetFields(targetFieldsFor(layerKeyOf(p.layer), p.target))
        setDocuments(p.documents.map((d) => ({ id: nextDocId++, kind: d.kind, document: d.document })))
        setLoaded(true)
      },
      (err) => {
        if (!cancelled) {
          setLoadError(describeError(err))
          setLoaded(true)
        }
      },
    )
    return () => {
      cancelled = true
    }
  }, [isNew, namespace, name])

  function applyTargetFields(f: { role: string; labelSelectorText: string; machineRef: string }) {
    setRole(f.role)
    setLabelSelectorText(f.labelSelectorText)
    setMachineRef(f.machineRef)
  }

  // buildWire returns null (after setting saveError/previewError itself)
  // when a label selector's JSON can't be parsed - the one place client-
  // side validation exists, because LabelSelector is a structured wire
  // field a Textarea can't populate without a JSON.parse first (lib/
  // patchTarget.ts). Every other rule is left to the apiserver's own CRD
  // validation, surfaced back through describeError (submit and show the
  // server's own rejection).
  function buildWire(setErr: (e: ErrorShape | null) => void): PatchInit | null {
    const invalid = (detail: string) => setErr({ title: t('error.invalidTarget'), detail })
    if (!cluster) {
      invalid(t('patch.chooseCluster'))
      return null
    }
    let target: PatchInit['target']
    try {
      target = buildPatchTarget(layerKeyOf(layer), role, labelSelectorText, machineRef)
    } catch (err) {
      const reason = (err as { reason?: string }).reason
      invalid(reason === 'selectorNotJson' ? t('error.selectorNotJson') : reason === 'selectorNotObject' ? t('error.selectorNotObject') : err instanceof Error ? err.message : String(err))
      return null
    }
    setErr(null)
    return {
      ref: { namespace: cluster.namespace, name: patchName },
      cluster,
      layer,
      priority,
      target,
      documents: documents.map((d) => ({ kind: d.kind, document: d.document })),
    }
  }


  async function save() {
    const wire = buildWire(setSaveError)
    if (!wire) return
    setSaving(true)
    try {
      if (isNew) {
        await patchClient.createPatch({ patch: wire })
        notifyDone(t('toast.patchCreated', { name: wire.ref?.name ?? '' }))
      } else {
        await patchClient.updatePatch({ patch: wire })
        notifyWrite('toast.patchSaved', { name: wire.ref?.name ?? '' })
      }
      navigate('/config')
    } catch (err) {
      setSaveError(describeError(err))
    } finally {
      setSaving(false)
    }
  }

  async function runPreview() {
    const wire = buildWire(setPreviewError)
    if (!wire) return
    const key = currentKey
    setPreviewing(true)
    setPreview(null)
    setPreviewedKey(null)
    try {
      const res = await patchClient.previewImpact({ patch: wire })
      setPreviewError(null)
      setPreviewedKey(key)
      setPreview({ rebootRequired: res.rebootRequired, installTimeOnly: res.installTimeOnly, unsupported: res.unsupported })
    } catch (err) {
      setPreviewError(describeError(err))
    } finally {
      setPreviewing(false)
    }
  }

  function addDocument() {
    setDocuments((prev) => [...prev, { id: nextDocId++, kind: 'SysctlConfig', document: defaultDocument('SysctlConfig'), fresh: true }])
  }
  function removeDocument(id: number) {
    setDocuments((prev) => prev.filter((d) => d.id !== id))
  }
  function updateDocument(id: number, next: Partial<DocItem>) {
    setDocuments((prev) => prev.map((d) => (d.id === id ? { ...d, ...next } : d)))
  }

  const currentKey = previewKey({
    cluster: cluster ? `${cluster.namespace}/${cluster.name}` : '',
    layer,
    priority,
    target: `${role}|${machineRef}|${labelSelectorText}`,
    documents,
  })
  const previewFresh = previewedKey === currentKey

  if (clusterError) return <ErrorAlert {...clusterError} />
  if (loadError) return <ErrorAlert {...loadError} />
  if (!loaded) return <PageSkeleton label={t('patch.loading')} />

  const canSave = canSavePatch({
    name: patchName,
    hasCluster: !!cluster,
    layer: layerKeyOf(layer),
    role,
    machineRef,
  })

  return (
    <>
      <PageTitle
        title={isNew ? t('patch.newTitle') : name!}
        description={t('kind.patch')}
        badges={!isNew && <Badge variant="outline">{enumLabel(ConfigLayer, layer)}</Badge>}
      />
      <div class="min-w-0 space-y-4">
        <Card id="basics" className="scroll-mt-section">
          <CardHeader>
            <CardTitle>{t('patch.basics')}</CardTitle>
            <CardDescription>{t('patch.intro')}</CardDescription>
          </CardHeader>
          <CardContent>
            <FieldGroup>
              <div class="grid gap-4 sm:grid-cols-2">
                <Field>
                  <FieldLabel htmlFor="patch-name">{t('col.name')}</FieldLabel>
                  <Input id="patch-name" value={patchName} disabled={!isNew} onInput={(e) => setPatchName((e.target as HTMLInputElement).value)} />
                  <FieldDescription>{t('patch.nameHelp')}</FieldDescription>
                </Field>
                <Field>
                  <FieldLabel htmlFor="patch-priority">{t('patch.priority')}</FieldLabel>
                  <Input
                    id="patch-priority"
                    type="number"
                    value={String(priority)}
                    onInput={(e) => setPriority(Number((e.target as HTMLInputElement).value) || 0)}
                  />
                  <FieldDescription>{t('patch.priorityHelp')}</FieldDescription>
                </Field>
              </div>
              <Field>
                <FieldLabel htmlFor="patch-layer">{t('patch.layer')}</FieldLabel>
                <Select
                  value={layer ? String(layer) : ''}
                  onValueChange={(v) => {
                    const l = Number(v) as ConfigLayer
                    setLayer(l)
                    // The layer picks the target: drop the old one.
                    applyTargetFields(targetFieldsFor(layerKeyOf(l), undefined))
                  }}
                >
                  <SelectTrigger id="patch-layer" className="w-full">
                    <SelectValue placeholder={t('patch.selectLayer')} />
                  </SelectTrigger>
                  <SelectContent>
                    {EDITABLE_LAYERS.map((l) => (
                      <SelectItem key={l.layer} value={String(l.layer)}>
                        {enumLabel(ConfigLayer, l.layer)}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
                <FieldDescription>{t('patch.layerHelp')}</FieldDescription>
                <ItemGroup>
                  {EDITABLE_LAYERS.map((l) => (
                    <Item key={l.layer} size="xs" variant={l.layer === layer ? 'outline' : 'default'}>
                      <ItemContent>
                        <ItemDescription>{t(l.descKey)}</ItemDescription>
                      </ItemContent>
                    </Item>
                  ))}
                </ItemGroup>
              </Field>

              {layer === ConfigLayer.ROLE && (
                <Field>
                  <FieldLabel htmlFor="patch-target-role">{t('patch.target')}</FieldLabel>
                  <Select value={role} onValueChange={setRole}>
                    <SelectTrigger id="patch-target-role" className="w-full">
                      <SelectValue placeholder={t('approve.selectRole')} />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="controlplane">{t('role.controlPlane')}</SelectItem>
                      <SelectItem value="worker">{t('role.worker')}</SelectItem>
                    </SelectContent>
                  </Select>
                </Field>
              )}

              {layer === ConfigLayer.SELECTOR && (
                <Field>
                  <FieldLabel htmlFor="patch-target-selector">{t('patch.target')}</FieldLabel>
                  <FieldDescription>{t('patch.selectorHint')}</FieldDescription>
                  <Textarea
                    id="patch-target-selector"
                    rows={5}
                    value={labelSelectorText}
                    onInput={(e) => setLabelSelectorText((e.target as HTMLTextAreaElement).value)}
                  />
                </Field>
              )}

              {layer === ConfigLayer.MACHINE && (
                <Field>
                  <FieldLabel htmlFor="patch-target-machine">{t('patch.target')}</FieldLabel>
                  <Select value={machineRef} onValueChange={setMachineRef}>
                    <SelectTrigger id="patch-target-machine" className="w-full">
                      <SelectValue placeholder={t('patch.selectMachine')} />
                    </SelectTrigger>
                    <SelectContent>
                      {[...new Set([...(machineRef ? [machineRef] : []), ...machines.map((m) => m.ref?.name ?? '').filter(Boolean)])].map((n) => (
                        <SelectItem key={n} value={n}>
                          {n}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                  {machines.length === 0 && <FieldDescription>{t('patch.noMachines')}</FieldDescription>}
                </Field>
              )}
            </FieldGroup>
          </CardContent>
        </Card>

        <Card id="documents" className="scroll-mt-section">
          <CardHeader>
            <CardTitle>{t('patch.documents')}</CardTitle>
            <CardDescription>{t('patch.documentsHelp')}</CardDescription>
            <CardAction>
              <Button size="sm" variant="outline" onClick={addDocument}>
                <PlusIcon data-icon="inline-start" aria-hidden="true" />
                {t('patch.addDocument')}
              </Button>
            </CardAction>
          </CardHeader>
          <CardContent className="space-y-3">
            {documents.length === 0 && <EmptyNote icon={FileCogIcon}>{t('patch.noDocuments')}</EmptyNote>}
            {documents.map((d) => (
              <PatchDocumentCard
                key={d.id}
                doc={d}
                startEditing={!!d.fresh}
                onChange={(next) => updateDocument(d.id, next)}
                onRemove={() => removeDocument(d.id)}
              />
            ))}
          </CardContent>
        </Card>

        <Card id="impact" className="scroll-mt-section">
          <CardHeader>
            <CardTitle>{t('patch.impact')}</CardTitle>
            <CardDescription>{t('patch.impactNote')}</CardDescription>
            <CardAction>
              <Button size="sm" variant="outline" disabled={previewing} onClick={runPreview}>
                {previewing ? <LoaderCircleIcon data-icon="inline-start" aria-hidden="true" /> : <EyeIcon data-icon="inline-start" aria-hidden="true" />}
                {previewing ? t('patch.previewing') : t('patch.previewButton')}
              </Button>
            </CardAction>
          </CardHeader>
          <CardContent className="space-y-3">
            {previewError && <ErrorAlert {...previewError} />}
            {!preview && !previewing && !previewError && (
              <Alert>
                <InfoIcon />
                <AlertTitle>{t('patch.previewNever')}</AlertTitle>
              </Alert>
            )}
            {preview && !previewFresh && (
              <Alert>
                <InfoIcon />
                <AlertTitle>{t('patch.previewStale')}</AlertTitle>
              </Alert>
            )}
            {preview && (
              <ItemGroup>
                <Item>
                  <ItemContent>
                    <ItemTitle>{t('patch.rebootRequired')}</ItemTitle>
                    <ItemDescription>{preview.rebootRequired ? t('patch.rebootYes') : t('patch.rebootNo')}</ItemDescription>
                  </ItemContent>
                  <ItemActions>
                    <Badge variant={preview.rebootRequired ? 'secondary' : 'outline'}>{preview.rebootRequired ? t('common.yes') : t('common.no')}</Badge>
                  </ItemActions>
                </Item>
                {preview.installTimeOnly.length > 0 && (
                  <>
                    <ItemSeparator />
                    <Item>
                      <ItemContent>
                        <ItemTitle>{t('patch.installTimeOnly')}</ItemTitle>
                        <ItemDescription>{t('patch.installTimeOnlyHelp')}</ItemDescription>
                        <div class="flex flex-wrap gap-1">
                          {preview.installTimeOnly.map((p) => (
                            <Badge key={p} variant="outline">
                              {p}
                            </Badge>
                          ))}
                        </div>
                      </ItemContent>
                    </Item>
                  </>
                )}
                {preview.unsupported.length > 0 && (
                  <>
                    <ItemSeparator />
                    <Item>
                      <ItemContent>
                        <ItemTitle>{t('patch.unsupported')}</ItemTitle>
                        <ItemDescription>{t('patch.unsupportedHelp')}</ItemDescription>
                        <div class="flex flex-wrap gap-1">
                          {preview.unsupported.map((p) => (
                            <Badge key={p} variant="destructive">
                              {p}
                            </Badge>
                          ))}
                        </div>
                      </ItemContent>
                    </Item>
                  </>
                )}
                {preview.installTimeOnly.length === 0 && preview.unsupported.length === 0 && (
                  <>
                    <ItemSeparator />
                    <Item>
                      <ItemContent>
                        <ItemDescription>{t('patch.previewAllClear')}</ItemDescription>
                      </ItemContent>
                    </Item>
                  </>
                )}
              </ItemGroup>
            )}
          </CardContent>
        </Card>

        {saveError && <ErrorAlert {...saveError} />}

        {!previewFresh && !previewing && (
          <Alert>
            <InfoIcon />
            <AlertDescription>{t('patch.saveReminder')}</AlertDescription>
          </Alert>
        )}

        <div class="flex flex-wrap items-center justify-between gap-2">
          <div class="flex gap-2">
            <Button disabled={!canSave || saving} onClick={save}>
              {saving ? t('patch.saving') : isNew ? t('patch.create') : t('patch.save')}
            </Button>
            <Button variant="ghost" onClick={() => navigate('/config')}>
              {t('common.cancel')}
            </Button>
          </div>
          {!isNew && <DeleteButton namespace={namespace!} name={name!} />}
        </div>
      </div>
    </>
  )
}

function DeleteButton({ namespace, name }: { namespace: string; name: string }) {
  const [open, setOpen] = useState(false)
  const [submitting, setSubmitting] = useState(false)
  const [error, setError] = useState<ErrorShape | null>(null)

  async function submit() {
    setSubmitting(true)
    setError(null)
    try {
      await patchClient.deletePatch({ patch: { namespace, name } })
      notifyDone(t('toast.patchDeleted', { name }))
      navigate('/config')
    } catch (err) {
      setError(describeError(err))
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <ConfirmDialog
      open={open}
      onOpenChange={setOpen}
      trigger={<Button variant="destructive">{t('patches.delete')}</Button>}
      title={t('patches.deleteTitle', { name })}
      description={t('patch.deleteDescription')}
      confirm={{ label: submitting ? t('patches.deleting') : t('patches.delete'), disabled: submitting, onClick: submit }}
    >
      {error && <ErrorAlert {...error} />}
    </ConfirmDialog>
  )
}
