import { useEffect, useState } from 'preact/hooks'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card'
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from '@/components/ui/dialog'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select'
import { Textarea } from '@/components/ui/textarea'
import type { MessageInitShape } from '@bufbuild/protobuf'
import { ErrorAlert } from '@/components/ErrorAlert'
import type { Cluster } from '@/gen/ichor/v1alpha1/cluster_pb'
import { ConfigLayer } from '@/gen/ichor/v1alpha1/node_pb'
import { PatchSchema } from '@/gen/ichor/v1alpha1/patch_pb'
import { clusterClient, patchClient } from '@/lib/connect'
import { enumLabel } from '@/lib/enum'
import { describeError } from '@/lib/errors'
import { parseLabelSelector, stringifyLabelSelector, targetKindOf, type TargetKind } from '@/lib/patchTarget'
import { navigate } from '@/router'

type ErrorShape = { title: string; detail: string }

// A Patch-shaped plain object, not the generated Message type: every field
// built here comes from form state, not a decoded response, so it never
// carries the generated type's own "$typeName" brand - MessageInitShape is
// the same loose, brand-free shape createClient's own call signatures
// already expect (confirmed against @connectrpc/connect's promise-client.d.ts).
type PatchInit = MessageInitShape<typeof PatchSchema>
type PatchDocumentInit = { kind: string; document: string }

// The layers a patch may actually set (CONFIG_LAYER_SYSTEM is generated by
// Ichor itself, never user-writable - architecture.md, "Patch layers").
const EDITABLE_LAYERS = [ConfigLayer.CLUSTER, ConfigLayer.ROLE, ConfigLayer.SELECTOR, ConfigLayer.MACHINE]

const DOCUMENT_KINDS = ['SysctlConfig', 'KernelModuleConfig', 'Config', 'VolumeConfig', 'UserVolumeConfig', 'RawVolumeConfig']

// PatchDetail is both the create form (/patches/new, namespace and name
// undefined) and the edit form (/patches/:namespace/:name) for a
// TalosConfigPatch, matching PatchService's own "full replace, no
// partial-field merge" shape (ADR 0035/0039's design question 2: the
// documents a patch carries are edited as opaque JSON per document, not
// through a generic schema-driven renderer - see that ADR for why).
export function PatchDetail({ namespace, name }: { namespace?: string; name?: string }) {
  const isNew = namespace === undefined || name === undefined

  const [loaded, setLoaded] = useState(isNew)
  const [loadError, setLoadError] = useState<ErrorShape | null>(null)

  const [clusters, setClusters] = useState<Cluster[]>([])
  const [patchName, setPatchName] = useState(name ?? '')
  const [cluster, setCluster] = useState<{ namespace: string; name: string } | undefined>(undefined)
  const [layer, setLayer] = useState<ConfigLayer>(ConfigLayer.UNSPECIFIED)
  const [priority, setPriority] = useState(0)
  const [targetKind, setTargetKind] = useState<TargetKind>('none')
  const [role, setRole] = useState('')
  const [labelSelectorText, setLabelSelectorText] = useState(stringifyLabelSelector(undefined))
  const [machineRef, setMachineRef] = useState('')
  const [documents, setDocuments] = useState<PatchDocumentInit[]>([])

  const [saveError, setSaveError] = useState<ErrorShape | string | null>(null)
  const [saving, setSaving] = useState(false)

  const [preview, setPreview] = useState<{ rebootRequired: boolean; installTimeOnly: string[]; unsupported: string[] } | null>(null)
  const [previewError, setPreviewError] = useState<ErrorShape | string | null>(null)
  const [previewing, setPreviewing] = useState(false)

  useEffect(() => {
    clusterClient.listClusters({}).then(
      (res) => setClusters(res.clusters),
      () => {
        /* The cluster picker degrades to "no options"; listPatches/getPatch below report the real error. */
      },
    )
  }, [])

  useEffect(() => {
    if (isNew) return
    let cancelled = false
    patchClient.getPatch({ patch: { namespace, name } }).then(
      (res) => {
        if (cancelled) return
        const p = res.patch
        if (!p) {
          setLoadError({ title: 'Not found', detail: 'No patch was returned.' })
          return
        }
        setPatchName(p.ref?.name ?? name)
        setCluster(p.cluster ? { namespace: p.cluster.namespace, name: p.cluster.name } : undefined)
        setLayer(p.layer)
        setPriority(p.priority)
        const kind = targetKindOf(p.target)
        setTargetKind(kind)
        if (kind === 'role') setRole(p.target?.role ?? '')
        if (kind === 'labelSelector') setLabelSelectorText(stringifyLabelSelector(p.target?.labelSelector))
        if (kind === 'machineRef') setMachineRef(p.target?.machineRef ?? '')
        setDocuments(p.documents)
        setLoaded(true)
      },
      (err) => {
        if (!cancelled) {
          setLoadError(describeError(err))
          setLoaded(true)
        }
      },
    )
    return () => {
      cancelled = true
    }
  }, [isNew, namespace, name])

  // buildWire returns null (after setting saveError/previewError itself)
  // when a label selector's JSON can't be parsed - the one place client-
  // side validation exists, because LabelSelector is a structured wire
  // field a Textarea can't populate without a JSON.parse first (lib/
  // patchTarget.ts). Every other rule is left to the apiserver's own CRD
  // validation, surfaced back through describeError (ADR 0039's design
  // question 1: no generic schema-driven form, submit and show the
  // server's own rejection).
  function buildWire(setErr: (e: string | null) => void): PatchInit | null {
    if (!cluster) {
      setErr('Choose a cluster first.')
      return null
    }
    let target: PatchInit['target']
    if (layer !== ConfigLayer.CLUSTER) {
      if (targetKind === 'role') {
        target = { role, labelSelector: undefined, machineRef: '' }
      } else if (targetKind === 'machineRef') {
        target = { role: '', labelSelector: undefined, machineRef }
      } else if (targetKind === 'labelSelector') {
        try {
          target = { role: '', labelSelector: parseLabelSelector(labelSelectorText), machineRef: '' }
        } catch (err) {
          setErr(err instanceof Error ? err.message : String(err))
          return null
        }
      }
    }
    setErr(null)
    return {
      ref: { namespace: namespace ?? cluster.namespace, name: patchName },
      cluster,
      layer,
      priority,
      target,
      documents,
    }
  }

  async function save() {
    const wire = buildWire(setSaveError)
    if (!wire) return
    setSaving(true)
    try {
      if (isNew) {
        await patchClient.createPatch({ patch: wire })
      } else {
        await patchClient.updatePatch({ patch: wire })
      }
      navigate('/patches')
    } catch (err) {
      setSaveError(describeError(err))
    } finally {
      setSaving(false)
    }
  }

  async function runPreview() {
    const wire = buildWire(setPreviewError)
    if (!wire) return
    setPreviewing(true)
    setPreview(null)
    try {
      const res = await patchClient.previewImpact({ patch: wire })
      setPreviewError(null)
      setPreview({ rebootRequired: res.rebootRequired, installTimeOnly: res.installTimeOnly, unsupported: res.unsupported })
    } catch (err) {
      setPreviewError(describeError(err))
    } finally {
      setPreviewing(false)
    }
  }

  function addDocument() {
    setDocuments((prev) => [...prev, { kind: DOCUMENT_KINDS[0], document: '{}' }])
  }
  function removeDocument(i: number) {
    setDocuments((prev) => prev.filter((_, idx) => idx !== i))
  }
  function updateDocument(i: number, next: Partial<PatchDocumentInit>) {
    setDocuments((prev) => prev.map((d, idx) => (idx === i ? { ...d, ...next } : d)))
  }

  if (loadError) return <ErrorAlert {...loadError} />
  if (!loaded) return <p class="mt-10 text-center text-sm text-muted-foreground">Loading patch…</p>

  const canSave = patchName !== '' && !!cluster && layer !== ConfigLayer.UNSPECIFIED && (layer === ConfigLayer.CLUSTER || targetKind !== 'none')

  return (
    <div class="mt-6 space-y-4">
      <Card>
        <CardHeader>
          <CardTitle>{isNew ? 'New patch' : `Edit ${name}`}</CardTitle>
        </CardHeader>
        <CardContent className="space-y-4">
          <div class="grid gap-3 sm:grid-cols-2">
            <div class="space-y-1">
              <Label htmlFor="patch-name">Name</Label>
              <Input
                id="patch-name"
                value={patchName}
                disabled={!isNew}
                onInput={(e) => setPatchName((e.target as HTMLInputElement).value)}
              />
            </div>
            <div class="space-y-1">
              <Label htmlFor="patch-cluster">Cluster</Label>
              <Select
                value={cluster ? `${cluster.namespace}/${cluster.name}` : ''}
                onValueChange={(v) => {
                  const [ns, n] = v.split('/')
                  setCluster({ namespace: ns, name: n })
                }}
              >
                <SelectTrigger id="patch-cluster" className="w-full">
                  <SelectValue placeholder="Select a cluster" />
                </SelectTrigger>
                <SelectContent>
                  {clusters
                    .filter((c) => c.ref)
                    .map((c) => (
                      <SelectItem key={`${c.ref!.namespace}/${c.ref!.name}`} value={`${c.ref!.namespace}/${c.ref!.name}`}>
                        {c.ref!.name}
                      </SelectItem>
                    ))}
                </SelectContent>
              </Select>
            </div>
            <div class="space-y-1">
              <Label htmlFor="patch-layer">Layer</Label>
              <Select
                value={layer ? String(layer) : ''}
                onValueChange={(v) => {
                  const l = Number(v) as ConfigLayer
                  setLayer(l)
                  if (l === ConfigLayer.CLUSTER) setTargetKind('none')
                }}
              >
                <SelectTrigger id="patch-layer" className="w-full">
                  <SelectValue placeholder="Select a layer" />
                </SelectTrigger>
                <SelectContent>
                  {EDITABLE_LAYERS.map((l) => (
                    <SelectItem key={l} value={String(l)}>
                      {enumLabel(ConfigLayer, l)}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            </div>
            <div class="space-y-1">
              <Label htmlFor="patch-priority">Priority</Label>
              <Input
                id="patch-priority"
                type="number"
                value={String(priority)}
                onInput={(e) => setPriority(Number((e.target as HTMLInputElement).value) || 0)}
              />
            </div>
          </div>

          {layer !== ConfigLayer.CLUSTER && layer !== ConfigLayer.UNSPECIFIED && (
            <div class="space-y-2 rounded-md border p-3">
              <Label htmlFor="patch-target-kind">Target</Label>
              <Select value={targetKind} onValueChange={(v) => setTargetKind(v as TargetKind)}>
                <SelectTrigger id="patch-target-kind" className="w-full">
                  <SelectValue placeholder="Select how to target machines" />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="role">Role</SelectItem>
                  <SelectItem value="labelSelector">Label selector</SelectItem>
                  <SelectItem value="machineRef">Machine reference</SelectItem>
                </SelectContent>
              </Select>

              {targetKind === 'role' && (
                <Select value={role} onValueChange={setRole}>
                  <SelectTrigger className="w-full">
                    <SelectValue placeholder="Select a role" />
                  </SelectTrigger>
                  <SelectContent>
                    <SelectItem value="controlplane">Control plane</SelectItem>
                    <SelectItem value="worker">Worker</SelectItem>
                  </SelectContent>
                </Select>
              )}

              {targetKind === 'machineRef' && (
                <Input
                  value={machineRef}
                  placeholder="TalosMachine name"
                  onInput={(e) => setMachineRef((e.target as HTMLInputElement).value)}
                />
              )}

              {targetKind === 'labelSelector' && (
                <div class="space-y-1">
                  <p class="text-xs text-muted-foreground">
                    JSON with "matchLabels" (a map) and/or "matchExpressions" (metav1.LabelSelector's own shape) -
                    checked by the apiserver on save, not here.
                  </p>
                  <Textarea
                    className="font-mono text-xs"
                    rows={5}
                    value={labelSelectorText}
                    onInput={(e) => setLabelSelectorText((e.target as HTMLTextAreaElement).value)}
                  />
                </div>
              )}
            </div>
          )}
        </CardContent>
      </Card>

      <Card>
        <CardHeader className="flex items-center justify-between">
          <CardTitle>Documents</CardTitle>
          <Button size="sm" variant="outline" onClick={addDocument}>
            Add document
          </Button>
        </CardHeader>
        <CardContent className="space-y-3">
          {documents.length === 0 && <p class="text-sm text-muted-foreground">No documents yet.</p>}
          {documents.map((d, i) => (
            <div key={i} class="space-y-2 rounded-md border p-3">
              <div class="flex items-center gap-2">
                <Select value={d.kind} onValueChange={(v) => updateDocument(i, { kind: v })}>
                  <SelectTrigger className="w-56">
                    <SelectValue />
                  </SelectTrigger>
                  <SelectContent>
                    {DOCUMENT_KINDS.map((k) => (
                      <SelectItem key={k} value={k}>
                        {k}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
                <Button size="sm" variant="ghost" onClick={() => removeDocument(i)}>
                  Remove
                </Button>
              </div>
              {/* document is opaque JSON on the wire (patch.proto) - shaped
                  exactly as TalosConfigPatchDocument's matching field would
                  unmarshal it; a Textarea plus the apiserver's own rejection
                  is this unit's whole answer to "schema-driven forms"
                  (ADR 0039's design question 1). */}
              <Textarea
                className="font-mono text-xs"
                rows={6}
                value={d.document}
                onInput={(e) => updateDocument(i, { document: (e.target as HTMLTextAreaElement).value })}
              />
            </div>
          ))}
        </CardContent>
      </Card>

      <Card>
        <CardHeader className="flex items-center justify-between">
          <CardTitle>Impact preview</CardTitle>
          <Button size="sm" variant="outline" disabled={previewing} onClick={runPreview}>
            {previewing ? 'Checking…' : 'Preview impact'}
          </Button>
        </CardHeader>
        <CardContent className="space-y-2 text-sm">
          <p class="text-muted-foreground">
            Classifies every field path this patch sets, not a diff against what's currently applied - run it
            again after editing, it does not update automatically.
          </p>
          {previewError && (typeof previewError === 'string' ? <ErrorAlert title="Invalid target" detail={previewError} /> : <ErrorAlert {...previewError} />)}
          {preview && (
            <div class="space-y-1">
              <div class="flex items-center gap-2">
                <span>Reboot required:</span>
                <Badge variant={preview.rebootRequired ? 'secondary' : 'outline'}>{preview.rebootRequired ? 'yes' : 'no'}</Badge>
              </div>
              <div>
                <span>Install-time only (needs reset and reinstall, a reboot does nothing for these):</span>{' '}
                {preview.installTimeOnly.length === 0 ? (
                  <span class="text-muted-foreground">none</span>
                ) : (
                  <div class="mt-1 flex flex-wrap gap-1">
                    {preview.installTimeOnly.map((p) => (
                      <Badge key={p} variant="outline" className="font-mono text-xs">
                        {p}
                      </Badge>
                    ))}
                  </div>
                )}
              </div>
              <div>
                <span>Unsupported by this cluster's pinned Talos version:</span>{' '}
                {preview.unsupported.length === 0 ? (
                  <span class="text-muted-foreground">none</span>
                ) : (
                  <div class="mt-1 flex flex-wrap gap-1">
                    {preview.unsupported.map((p) => (
                      <Badge key={p} variant="destructive" className="font-mono text-xs">
                        {p}
                      </Badge>
                    ))}
                  </div>
                )}
              </div>
            </div>
          )}
        </CardContent>
      </Card>

      {saveError && (typeof saveError === 'string' ? <ErrorAlert title="Invalid target" detail={saveError} /> : <ErrorAlert {...saveError} />)}

      <div class="flex items-center justify-between">
        <div class="flex gap-2">
          <Button disabled={!canSave || saving} onClick={save}>
            {saving ? 'Saving…' : isNew ? 'Create' : 'Save'}
          </Button>
          <Button variant="ghost" onClick={() => navigate('/patches')}>
            Cancel
          </Button>
        </div>
        {!isNew && <DeleteButton namespace={namespace!} name={name!} />}
      </div>
    </div>
  )
}

function DeleteButton({ namespace, name }: { namespace: string; name: string }) {
  const [open, setOpen] = useState(false)
  const [submitting, setSubmitting] = useState(false)
  const [error, setError] = useState<ErrorShape | null>(null)

  async function submit() {
    setSubmitting(true)
    setError(null)
    try {
      await patchClient.deletePatch({ patch: { namespace, name } })
      navigate('/patches')
    } catch (err) {
      setError(describeError(err))
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger asChild>
        <Button variant="destructive">Delete</Button>
      </DialogTrigger>
      <DialogContent>
        <DialogHeader>
          <DialogTitle>Delete {name}?</DialogTitle>
          <DialogDescription>
            This removes the TalosConfigPatch outright. Nodes it targets stop receiving its values the next
            time the controller renders their configuration.
          </DialogDescription>
        </DialogHeader>
        {error && <ErrorAlert {...error} />}
        <DialogFooter>
          <Button variant="ghost" onClick={() => setOpen(false)}>
            Cancel
          </Button>
          <Button variant="destructive" disabled={submitting} onClick={submit}>
            {submitting ? 'Deleting…' : 'Delete'}
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  )
}
